package dartanalysis

import (
	"context"
	"crypto/sha256"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	gotreesitter "github.com/odvcencio/gotreesitter"

	"github.com/maxqstudio/DoctorCode/internal/detector"
	"github.com/maxqstudio/DoctorCode/internal/model"
)

const (
	ruleLogic    = "DART-LOGIC-DUPLICATE-CONDITION"
	ruleSecurity = "DART-SEC-HARDCODED-CREDENTIAL"
	ruleSimplify = "DART-SIMPLIFY-BOOL-RETURN"
)

type Analyzer struct{}

func New() *Analyzer             { return &Analyzer{} }
func (a *Analyzer) Name() string { return "dart/gotreesitter-v1" }

func (a *Analyzer) Descriptor() detector.Descriptor {
	return detector.Descriptor{
		ID:         a.Name(),
		Language:   "Dart",
		Extensions: []string{".dart"},
		Parser: detector.ParserContract{
			Kind:       detector.ParserEmbeddedAST,
			Provider:   "gotreesitter v0.55.1 Dart",
			FailClosed: true,
		},
		Availability:     detector.AvailabilityContract{Mode: detector.AvailabilitySourceOnly},
		EvidenceBoundary: "Pure-Go strict Dart AST. M26 proves only direct literal credential bindings, opposite boolean return branches, and repeated conditions on stable bool parameters. Generated files are excluded. Nullability, async runtime, imports/packages, Flutter lifecycle, routing, state-management frameworks, codegen, dynamic reachability, DEADCODE, BLOAT, and safe autofix remain NOT_PROVEN.",
		Rules: []detector.RuleMetadata{
			{ID: ruleLogic, Category: model.CategoryLogic, SafeAutofix: false},
			{ID: ruleSecurity, Category: model.CategorySecurity, SafeAutofix: false},
			{ID: ruleSimplify, Category: model.CategorySimplify, SafeAutofix: false},
		},
		Benchmark: detector.BenchmarkContract{SchemaVersion: 1, Languages: []string{"Dart"}},
	}
}

type parsedFile struct {
	rel    string
	source []byte
	syntax *syntaxDocument
}

func (a *Analyzer) Analyze(ctx context.Context, root string) ([]model.Finding, error) {
	var paths []string
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		if entry.IsDir() {
			if path != root && ignoredDirectory(entry.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if entry.Type()&fs.ModeSymlink != 0 {
			return nil
		}
		if strings.EqualFold(filepath.Ext(path), ".dart") {
			paths = append(paths, path)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(paths) == 0 {
		return nil, fmt.Errorf("%w: no Dart source files", detector.ErrUnavailable)
	}
	sort.Strings(paths)
	var findings []model.Finding
	for _, path := range paths {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return nil, err
		}
		rel = filepath.ToSlash(rel)
		if generatedSuffix(rel) {
			continue
		}
		source, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read Dart source %s: %w", rel, err)
		}
		if generatedMarker(source) {
			continue
		}
		if strings.IndexByte(string(source), 0) >= 0 {
			return nil, fmt.Errorf("Dart syntax validation failed for %s: NUL byte", rel)
		}
		syntax, err := parseSyntax(source)
		if err != nil {
			return nil, fmt.Errorf("Dart syntax validation failed for %s: %w", rel, err)
		}
		file := &parsedFile{rel: rel, source: source, syntax: syntax}
		findings = append(findings, securityFindings(file)...)
		findings = append(findings, functionFindings(file)...)
	}
	return findings, nil
}

func ignoredDirectory(name string) bool {
	switch strings.ToLower(name) {
	case ".git", ".hg", ".svn", ".idea", ".vscode", ".dart_tool", ".venv", "venv", "node_modules", "vendor", "dist", "build", "target", "coverage", "generated", "testdata":
		return true
	default:
		return false
	}
}

func generatedSuffix(path string) bool {
	lower := strings.ToLower(path)
	return strings.HasSuffix(lower, ".g.dart") || strings.HasSuffix(lower, ".freezed.dart")
}

func generatedMarker(source []byte) bool {
	prefix := source
	if len(prefix) > 1024 {
		prefix = prefix[:1024]
	}
	lower := strings.ToLower(string(prefix))
	for _, marker := range []string{"generated code", "code generated", "generated by", "do not edit", "do not modify by hand", "@generated", "<auto-generated"} {
		if strings.Contains(lower, marker) {
			return true
		}
	}
	return false
}

func securityFindings(file *parsedFile) []model.Finding {
	var out []model.Finding
	language := file.syntax.language
	gotreesitter.Walk(file.syntax.tree.RootNode(), func(node *gotreesitter.Node, _ int) gotreesitter.WalkAction {
		kind := node.Type(language)
		if kind != "static_final_declaration" && kind != "initialized_identifier" {
			return gotreesitter.WalkContinue
		}
		if node.NamedChildCount() != 2 {
			return gotreesitter.WalkContinue
		}
		ident, literal := node.NamedChild(0), node.NamedChild(1)
		if ident == nil || literal == nil || ident.Type(language) != "identifier" || literal.Type(language) != "string_literal" {
			return gotreesitter.WalkContinue
		}
		if literal.NamedChildCount() != 0 {
			return gotreesitter.WalkContinue
		}
		name := nodeText(file.source, ident)
		if !credentialLike(name) {
			return gotreesitter.WalkContinue
		}
		raw := nodeText(file.source, literal)
		if len(raw) < 2 || raw[0] != '"' || raw[len(raw)-1] != '"' {
			return gotreesitter.WalkContinue
		}
		value, err := strconv.Unquote(raw)
		if err != nil || obviousPlaceholder(value) {
			return gotreesitter.WalkContinue
		}
		digest := sha256.Sum256([]byte(value))
		out = append(out, newFinding(
			ruleSecurity, model.CategorySecurity, model.SeverityHigh, model.ConfidenceSuspicious,
			file.rel, line(node),
			"credential-like Dart binding contains a direct hardcoded string literal",
			[]string{fmt.Sprintf("identifier=%s literal_bytes=%d sha256_prefix=%x", name, len(value), digest[:6]), "secret value redacted; interpolation and generated files excluded"},
		))
		return gotreesitter.WalkSkipChildren
	})
	return out
}

func credentialLike(name string) bool {
	var cleaned strings.Builder
	for _, r := range strings.ToLower(name) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			cleaned.WriteRune(r)
		}
	}
	s := cleaned.String()
	for _, marker := range []string{"password", "passwd", "secret", "apikey", "token", "privatekey", "accesskey"} {
		if s == marker || strings.HasSuffix(s, marker) {
			return true
		}
	}
	return false
}

func obviousPlaceholder(value string) bool {
	s := strings.ToLower(strings.TrimSpace(value))
	if s == "" {
		return true
	}
	for _, marker := range []string{"placeholder", "dummy", "example", "changeme", "change-me", "notasecret", "not-a-secret", "your_", "your-", "test-only", "<"} {
		if strings.Contains(s, marker) {
			return true
		}
	}
	return false
}

func functionFindings(file *parsedFile) []model.Finding {
	root := file.syntax.tree.RootNode()
	lang := file.syntax.language
	var findings []model.Finding
	findings = append(findings, functionsIn(file, root)...)
	for i := 0; i < root.NamedChildCount(); i++ {
		item := root.NamedChild(i)
		if item == nil || item.Type(lang) != "class_definition" {
			continue
		}
		for j := 0; j < item.NamedChildCount(); j++ {
			body := item.NamedChild(j)
			if body != nil && body.Type(lang) == "class_body" {
				findings = append(findings, functionsIn(file, body)...)
			}
		}
	}
	return findings
}

func functionsIn(file *parsedFile, container *gotreesitter.Node) []model.Finding {
	lang := file.syntax.language
	var out []model.Finding
	for i := 1; i < container.NamedChildCount(); i++ {
		body := container.NamedChild(i)
		if body == nil || body.Type(lang) != "function_body" {
			continue
		}
		sig := container.NamedChild(i - 1)
		if sig == nil {
			continue
		}
		switch sig.Type(lang) {
		case "function_signature":
		case "method_signature":
			if sig.NamedChildCount() != 1 {
				continue
			}
			sig = sig.NamedChild(0)
			if sig == nil || sig.Type(lang) != "function_signature" {
				continue
			}
		default:
			continue
		}
		if body.NamedChildCount() != 1 || body.NamedChild(0).Type(lang) != "block" {
			continue
		}
		block := body.NamedChild(0)
		// Unknown nested binding/callback behavior is a proof barrier.
		if hasNestedCallable(file, block) {
			continue
		}
		params := stableBoolParameters(file, sig, block)
		if len(params) == 0 {
			continue
		}
		returnsBool := sig.NamedChildCount() > 0 && nodeText(file.source, sig.NamedChild(0)) == "bool"
		for j := 0; j < block.NamedChildCount(); j++ {
			stmt := block.NamedChild(j)
			if stmt == nil || stmt.Type(lang) != "if_statement" {
				continue
			}
			if returnsBool {
				if finding, ok := simplifyIf(file, stmt, params); ok {
					out = append(out, finding)
				}
			}
			if finding, ok := duplicateIf(file, stmt, params); ok {
				out = append(out, finding)
			}
		}
	}
	return out
}

func hasNestedCallable(file *parsedFile, body *gotreesitter.Node) bool {
	lang := file.syntax.language
	nested := false
	gotreesitter.Walk(body, func(node *gotreesitter.Node, _ int) gotreesitter.WalkAction {
		switch node.Type(lang) {
		case "local_function_declaration", "function_expression", "lambda_expression":
			nested = true
			return gotreesitter.WalkStop
		}
		return gotreesitter.WalkContinue
	})
	return nested
}

func stableBoolParameters(file *parsedFile, sig, body *gotreesitter.Node) map[string]bool {
	lang := file.syntax.language
	params := map[string]bool{}
	for i := 0; i < sig.NamedChildCount(); i++ {
		children := sig.NamedChild(i)
		if children == nil || children.Type(lang) != "formal_parameter_list" {
			continue
		}
		for j := 0; j < children.NamedChildCount(); j++ {
			param := children.NamedChild(j)
			if param == nil || param.Type(lang) != "formal_parameter" || param.NamedChildCount() != 2 {
				continue
			}
			typ, name := param.NamedChild(0), param.NamedChild(1)
			if typ.Type(lang) != "type_identifier" || nodeText(file.source, typ) != "bool" || name.Type(lang) != "identifier" {
				continue
			}
			params[nodeText(file.source, name)] = true
		}
	}
	if len(params) == 0 {
		return params
	}
	gotreesitter.Walk(body, func(node *gotreesitter.Node, _ int) gotreesitter.WalkAction {
		switch node.Type(lang) {
		case "assignment_expression":
			if node.NamedChildCount() < 1 {
				return gotreesitter.WalkContinue
			}
			left := node.NamedChild(0)
			for i := 0; i < left.NamedChildCount(); i++ {
				ident := left.NamedChild(i)
				if ident.Type(lang) == "identifier" {
					delete(params, nodeText(file.source, ident))
				}
			}
			if left.Type(lang) == "identifier" {
				delete(params, nodeText(file.source, left))
			}
		case "initialized_identifier", "static_final_declaration":
			if node.NamedChildCount() > 0 {
				name := node.NamedChild(0)
				if name.Type(lang) == "identifier" {
					delete(params, nodeText(file.source, name))
				}
			}
		}
		return gotreesitter.WalkContinue
	})
	return params
}

func simplifyIf(file *parsedFile, node *gotreesitter.Node, params map[string]bool) (model.Finding, bool) {
	lang := file.syntax.language
	if node.NamedChildCount() != 3 {
		return model.Finding{}, false
	}
	condition, yes, no := node.NamedChild(0), node.NamedChild(1), node.NamedChild(2)
	if condition.Type(lang) != "identifier" || !params[nodeText(file.source, condition)] {
		return model.Finding{}, false
	}
	yesValue, yesOK := returnBool(file, yes)
	noValue, noOK := returnBool(file, no)
	if !yesOK || !noOK || yesValue == noValue {
		return model.Finding{}, false
	}
	return newFinding(
		ruleSimplify, model.CategorySimplify, model.SeverityLow, model.ConfidenceHigh,
		file.rel, line(node),
		"Dart if/else returns opposite boolean literals for the same stable bool parameter",
		[]string{"AST-proven direct bool parameter and opposite one-statement return branches", "safe_autofix=false"},
	), true
}

func returnBool(file *parsedFile, block *gotreesitter.Node) (bool, bool) {
	lang := file.syntax.language
	if block.Type(lang) != "block" || block.NamedChildCount() != 1 {
		return false, false
	}
	stmt := block.NamedChild(0)
	if stmt.Type(lang) != "return_statement" || stmt.NamedChildCount() != 1 {
		return false, false
	}
	v := stmt.NamedChild(0)
	switch v.Type(lang) {
	case "true":
		return true, true
	case "false":
		return false, true
	default:
		return false, false
	}
}

func duplicateIf(file *parsedFile, node *gotreesitter.Node, params map[string]bool) (model.Finding, bool) {
	lang := file.syntax.language
	if node.NamedChildCount() != 3 {
		return model.Finding{}, false
	}
	condition, alternative := node.NamedChild(0), node.NamedChild(2)
	if condition.Type(lang) != "identifier" || alternative.Type(lang) != "if_statement" || alternative.NamedChildCount() < 2 {
		return model.Finding{}, false
	}
	repeated := alternative.NamedChild(0)
	if repeated.Type(lang) != "identifier" {
		return model.Finding{}, false
	}
	name := nodeText(file.source, condition)
	if !params[name] || name != nodeText(file.source, repeated) {
		return model.Finding{}, false
	}
	return newFinding(
		ruleLogic, model.CategoryLogic, model.SeverityMedium, model.ConfidenceHigh,
		file.rel, line(alternative),
		"Dart else-if repeats the same unmodified bool parameter condition",
		[]string{fmt.Sprintf("AST-proven repeated bool parameter %q in one if/else-if chain", name), "mutation or nested callable prevents finding"},
	), true
}

func nodeText(source []byte, node *gotreesitter.Node) string {
	if node == nil {
		return ""
	}
	start, end := int(node.StartByte()), int(node.EndByte())
	if start < 0 || end < start || end > len(source) {
		return ""
	}
	return string(source[start:end])
}

func line(node *gotreesitter.Node) int { return int(node.StartPoint().Row) + 1 }

func newFinding(rule string, category model.Category, severity model.Severity, confidence model.Confidence, path string, at int, summary string, evidence []string) model.Finding {
	return model.Finding{
		ID:           detector.FindingID(rule, path, at, summary),
		RuleID:       rule,
		Category:     category,
		Severity:     severity,
		Confidence:   confidence,
		Path:         path,
		LineStart:    at,
		LineEnd:      at,
		Summary:      summary,
		Evidence:     evidence,
		Verification: []string{"review source scope and compile with the project Dart toolchain", "run project tests"},
		SafeAutofix:  false,
	}
}
